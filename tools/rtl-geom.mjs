// rtl-geom.mjs — ★ (ر16-ج، ٦ جمادى الأولى ١٤٤٨هـ) أحكامٌ هندسية صغيرة يستعملها فحص الاتجاه (rtl-audit.mjs)، في وحدةٍ وحدها ليمتحنها
// الفحص الذاتي للأدوات (selftest-tools.mjs) بلا كروم ولا شبكة: rtl-audit.mjs نصٌّ يعمل عند استيراده، فلا يُستورد في الحزام.
//
//   sgn(v, tol)  ⇒ 1 إن زاد v على التسامح، و‎-1‎ إن نقص عن سالبه، و0 داخل التسامح وعلى حدّيه (‎|v| <= tol‎)
//   ltrSideFlipped(d0, d1, tol) ⇒ صادقٌ إن كان لفرق الأصل (يسار ناقص يمين) إشارةٌ وانقلبت في المعرَّب. فرقٌ على حدّ التسامح تمامًا
//     إشارتُه صفر فلا انقلاب — وكان فحص box-mirrored-ltr يتخطّى ‎|d0| < tol‎ وحده، فيمرّ ‎|d0| == tol‎ إلى مقارنة صفرين (‎-0 === 0‎)
//     ويُعدّ «انعكس» والحشوة هي هي قبل وبعد (pl=2.9 pr=0 في بنود قوائم claude.com: الصنف 01ee2f7d7487 في ر16-ب)
export const sgn = (v, tol) => (v > tol ? 1 : v < -tol ? -1 : 0);
export const ltrSideFlipped = (d0, d1, tol) => sgn(d0, tol) !== 0 && sgn(d1, tol) === -sgn(d0, tol);
// ★ (ر18، ٨ جمادى الأولى ١٤٤٨هـ — ما حمله ر16-ج) sideNotMirrored(d0, d1, tol) ⇒ صادقٌ إن كان لفرق الأصل إشارةٌ وبقيت هي هي في المعرَّب (عنصرٌ RTL
//   لم تنعكس حشوته أو هامشه أو حدّه أو إزاحته). فرقٌ على حدّ التسامح تمامًا إشارتُه صفر فلا يُحكم عليه — وكان فرع box-not-mirrored يتخطّى
//   ‎|d0| < tol‎ وحده، فيمرّ ‎|d0| == tol‎ وفرقٌ متناظر في المعرَّب إلى مقارنة صفرين فيُعدّ «لم ينعكس» (الخطأ نفسه الذي أصلحه ر16-ج في box-mirrored-ltr)
export const sideNotMirrored = (d0, d1, tol) => sgn(d0, tol) !== 0 && sgn(d1, tol) === sgn(d0, tol);
// ★ (ر24-ب1، ١٢ جمادى الأولى ١٤٤٨هـ) insideAtRest(left, right, scrollX, vw) ⇒ صادقٌ إن كان العنصر داخل عرض الصفحة «في الراحة»: قبل أي تمريرٍ
//   أفقي، أي بمستطيله في الإطار مضافًا إليه تمرير الصفحة الأفقي الحاضر (‎scrollX‎، وهو صفرٌ في الراحة في الاتجاهين)، بتسامح بكسلٍ في الجهتين.
//   كان حكم الخروج (clipState في جامع rtl-audit.mjs) بمستطيل الإطار كما هو: وكروم في محاكاة الجوال (‎mobile: true‎، عرض 390) يفتح الصفحةَ
//   RTL التي تفيض أفقيًّا مُمرَّرةً إلى طرفها الأيسر (‎scrollX = −(scrollWidth − clientWidth)‎، قِيس على صفحةٍ اصطناعية بلا سكربت ولا إضافة:
//   ‎−76‎ في الجوال و0 بدونه)، والمرجع LTR في الراحة. فيُرى ما هو داخل الصفحة عند حافّتها اليمنى خارجًا بقدر التمرير (عنصرٌ في ‎211–325‎
//   يُقاس ‎286–400‎ في إطارٍ عرضه 390)، ويُرى ما خرج فعلًا إلى فسحة الفيض اليسرى داخلًا. والعنصر في سلفٍ ثابت (fixed) لا يتحرّك بالتمرير،
//   فيُمرَّر له التمرير صفرًا (الجامع يفعل ذلك)
export const insideAtRest = (left, right, scrollX, vw) => left + scrollX >= -1 && right + scrollX <= vw + 1;
// ★ (ر24-ب2، ١٢ جمادى الأولى ١٤٤٨هـ — مراجعة Codex CX-007) islandDrift(r, e, tol) ⇒ أمانة الجزيرة: هندسة ما داخل جزيرة LTR (pre وcode وkbd وsamp
//   والرياضيات وهيكل المسار) تساوي الأصل. r وe سجلّا جذر الجزيرة في الأصل والمعرَّب، وفي كلٍّ ik: ‎[[مسار الحفيد من الجذر، x، y، العرض، الارتفاع]…]‎
//   نسبةً إلى الجذر. لا حكم إن تغيّر مقاس الجذر نفسه (أكثر من بكسل: نصٌّ حوله التفّ فتغيّر سطرُه، أو خطٌّ غيّر عرضه) — فالمقارنة لا تصحّ.
//   وإلا فكلُّ حفيدٍ في السجلّين بالمسار نفسه يجب أن يبقى في موضعه ومقاسه بتسامح tol. يرجع null أو ‎{n: عدد الحائدين، of: عدد المقارَنين،
//   first: {p، dx، dw}}‎ لأولهم
export const islandDrift = (r, e, tol) => {
  if (!r || !e || !r.ik || !e.ik || Math.abs(r.w - e.w) > 1 || Math.abs(r.h - e.h) > 1) return null;
  const m = new Map(r.ik.map((k) => [k[0], k]));
  let n = 0, of = 0, first = null;
  for (const k of e.ik) {
    const o = m.get(k[0]); if (!o) continue;
    of++;
    if (Math.abs(k[1] - o[1]) > tol || Math.abs(k[2] - o[2]) > tol || Math.abs(k[3] - o[3]) > tol || Math.abs(k[4] - o[4]) > tol) {
      n++; if (!first) first = { p: k[0], dx: Math.round(k[1] - o[1]), dw: Math.round(k[3] - o[3]) };
    }
  }
  return n ? { n, of, first } : null;
};
